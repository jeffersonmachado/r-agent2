const crypto = require('crypto');
const fs = require('fs');
const path = require('path');
const models = require('../../db/models');

function makeId(prefix) {
  return `${prefix}_${crypto.randomUUID()}`;
}

function normalizeText(v) {
  if (v == null) return null;
  const s = String(v).trim();
  return s ? s : null;
}

function splitAclList(raw) {
  const s = normalizeText(raw);
  if (!s) return [];
  return s
    .split(/[\n,;]+/g)
    .map((x) => String(x).trim())
    .filter(Boolean);
}

function toAclSectionName({ tenantKey, aclId }) {
  // Stable + safe section key, independent from user-facing name.
  return `${tenantKey}__acl_${String(aclId)}`;
}

function renderAclConf({ items }) {
  const lines = [];
  lines.push('; AUTO-GENERATED by r-agent2 (PBX ACL catalog)');
  lines.push(`; generated_at=${new Date().toISOString()}`);
  lines.push('; Do not edit this file manually.');
  lines.push('');

  for (const it of items) {
    if (!it?.enabled) continue;
    const tenantKey = String(it.tenantKey || '').trim();
    if (!tenantKey) continue;
    const section = toAclSectionName({ tenantKey, aclId: it.id });

    lines.push(`[${section}]`);
    lines.push(`; name=${String(it.name || '').replace(/\r?\n/g, ' ').slice(0, 200)}`);
    if (it.description) lines.push(`; description=${String(it.description).replace(/\r?\n/g, ' ').slice(0, 220)}`);

    const deny = splitAclList(it.deny);
    const permit = splitAclList(it.permit);
    for (const d of deny) lines.push(`deny=${d}`);
    for (const p of permit) lines.push(`permit=${p}`);
    lines.push('');
  }

  return lines.join('\n');
}

async function syncAsteriskAclConf() {
  const PbxAcl = models.PbxAcl();
  const items = await PbxAcl.findAll({ order: [['tenantKey', 'ASC'], ['name', 'ASC']] });
  const content = renderAclConf({ items: items.map((r) => r.toJSON()) });

  const outPath = process.env.PBX_ACL_CONF_PATH || '/app/api/data/pbx-acl.generated.conf';
  const dir = path.dirname(outPath);
  fs.mkdirSync(dir, { recursive: true });

  const tmp = `${outPath}.tmp`;
  fs.writeFileSync(tmp, content, 'utf8');
  fs.renameSync(tmp, outPath);

  return { ok: true, path: outPath, bytes: Buffer.byteLength(content, 'utf8') };
}

async function listAcls({ tenantKey }) {
  const PbxAcl = models.PbxAcl();
  const items = await PbxAcl.findAll({
    where: { tenantKey },
    order: [['name', 'ASC']],
  });
  return items.map((r) => r.toJSON());
}

async function upsertAcl({ tenantKey, payload, actorUserId = null }) {
  const PbxAcl = models.PbxAcl();
  const id = (payload?.id ?? null) ? String(payload.id).trim() : null;
  const name = normalizeText(payload?.name);
  if (!name) {
    const err = new Error('acl_name_required');
    err.code = 'acl_name_required';
    throw err;
  }

  const description = normalizeText(payload?.description);
  const enabled = payload?.enabled === false ? false : true;
  const deny = normalizeText(payload?.deny);
  const permit = normalizeText(payload?.permit);

  let row = null;
  if (id) {
    row = await PbxAcl.findOne({ where: { tenantKey, id } });
  }
  if (!row) {
    row = await PbxAcl.findOne({ where: { tenantKey, name } });
  }

  const out = row
    ? await row.update({ name, description, enabled, deny, permit })
    : await PbxAcl.create({ id: makeId('pbx_acl'), tenantKey, name, description, enabled, deny, permit });

  // Best-effort: regenerate asterisk acl.conf so endpoints can reference updated ACLs.
  try {
    await syncAsteriskAclConf();
  } catch (_) {}

  // Best-effort audit event (optional)
  try {
    // eslint-disable-next-line global-require
    const { logAction } = require('../auditService');
    if (actorUserId) logAction({
      agentId: actorUserId,
      tenantId: tenantKey,
      action: 'pbx.acls.upsert',
      resource: 'pbx_acl',
      resourceId: out.id,
      details: { tenantKey, id: out.id, name: out.name, enabled: out.enabled },
    });
  } catch (_) {}

  return out.toJSON();
}

async function deleteAcl({ tenantKey, id, actorUserId = null }) {
  const PbxAcl = models.PbxAcl();
  const aclId = (id ?? null) ? String(id).trim() : null;
  if (!aclId) {
    const err = new Error('acl_id_required');
    err.code = 'acl_id_required';
    throw err;
  }
  const row = await PbxAcl.findOne({ where: { tenantKey, id: aclId } });
  if (!row) return { ok: true, removed: false };
  await row.destroy();

  try {
    await syncAsteriskAclConf();
  } catch (_) {}

  try {
    // eslint-disable-next-line global-require
    const { logAction } = require('../auditService');
    if (actorUserId) logAction({
      agentId: actorUserId,
      tenantId: tenantKey,
      action: 'pbx.acls.delete',
      resource: 'pbx_acl',
      resourceId: aclId,
      details: { tenantKey, id: aclId },
    });
  } catch (_) {}

  return { ok: true, removed: true };
}

async function resolveAsteriskAclSectionById({ tenantKey, aclId }) {
  const id = (aclId ?? null) ? String(aclId).trim() : null;
  if (!id) return null;
  const PbxAcl = models.PbxAcl();
  const row = await PbxAcl.findOne({ where: { tenantKey, id } });
  if (!row) return null;
  const json = row.toJSON();
  if (!json.enabled) return null;
  return toAclSectionName({ tenantKey, aclId: json.id });
}

module.exports = {
  listAcls,
  upsertAcl,
  deleteAcl,
  syncAsteriskAclConf,
  resolveAsteriskAclSectionById,
  toAclSectionName,
};

