/**
 * Flattened page context consumed by orchestrator config builders.
 * @typedef {Record<string, unknown>} OrchestratorBuilderContext
 */

/**
 * Flatten grouped page context sections into a single object for config builders.
 * @param {OrchestratorBuilderContextGroups} groups
 * @returns {OrchestratorBuilderContext}
 */
export function buildOrchestratorBuilderContext({
  formAndFlags,
  state,
  actions,
  pipelineRefs,
  sharedServices,
  tenantServices,
  standardServices,
}) {
  return {
    ...formAndFlags,
    ...state,
    ...actions,
    ...pipelineRefs,
    ...sharedServices,
    ...tenantServices,
    ...standardServices,
  };
}

